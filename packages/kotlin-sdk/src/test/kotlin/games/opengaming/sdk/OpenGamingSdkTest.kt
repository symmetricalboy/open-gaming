    @Test
    fun `matches TypeScript and Unity golden DID keys, CIDv1s, rkeys, and ECDSA signatures byte for byte`() = runTest {
        val k1 = OpenGamingSigningKey.load(PRIV1_B64URL)
        val k2 = OpenGamingSigningKey.load(PRIV2_B64URL)

        assertEquals(EXPECTED_K1_DID, k1.publicDidKey)
        assertEquals(EXPECTED_K2_DID, k2.publicDidKey)
        assertEquals(PRIV1_B64URL, k1.exportPrivateKeyBase64Url())

        // 1. Deterministic rkey parity
        assertEquals("first-flight-1c5556424d2cb8f203ad", OpenGamingLeaderboards.getUnlockRkey(ACH_FIRST_FLIGHT))
        assertEquals(
            "rhythm-stage-1-best-2ee7912d017a611c2c1e",
            OpenGamingLeaderboards.getOverwriteBestScoreRkey(
                LB_RHYTHM,
                mapOf("mode" to "4k", "scroll" to "upscroll"),
                "2026-11-21"
            )
        )

        // 2. Signed unlock CIDv1 & TypeScript signature verification
        val (signedUnlock, unlockCid) = OpenGamingAttestation.createSignedUnlock(
            unlock = AchievementUnlockRecord(
                achievement = ACH_FIRST_FLIGHT,
                game = GAME_URI,
                unlockedAt = "2026-11-21T12:00:00.000Z",
                note = "Cleared on mobile!"
            ),
            playerDid = ALICE_DID,
            issuerDid = GAME_DID,
            signingKey = k1,
            rkey = "first-flight-unlock"
        )
        assertEquals(EXPECTED_UNLOCK_CID, unlockCid)

        val ktJson = OpenGamingJson.decodeFromString<JsonObject>(OpenGamingJson.encodeToString(signedUnlock))
        val ktVerify = OpenGamingAttestation.verifyRecordAttestation(
            record = ktJson,
            playerDid = ALICE_DID,
            recordUri = "at://$ALICE_DID/${OpenGamingConstants.Nsids.ACHIEVEMENT_UNLOCK}/first-flight-unlock",
            publicDidKey = EXPECTED_K1_DID
        )
        assertTrue(ktVerify.verified)

        val tsSignedUnlock = signedUnlock.copy(
            signatures = listOf(signedUnlock.signatures!!.first().copy(signature = BytesWrapper(TS_UNLOCK_SIG)))
        )
        val tsVerify = OpenGamingAttestation.verifyRecordAttestation(
            record = OpenGamingJson.decodeFromString(OpenGamingJson.encodeToString(tsSignedUnlock)),
            playerDid = ALICE_DID,
            recordUri = "at://$ALICE_DID/${OpenGamingConstants.Nsids.ACHIEVEMENT_UNLOCK}/first-flight-unlock",
            publicDidKey = EXPECTED_K1_DID
        )
        assertTrue(tsVerify.verified)

        // 3. Multi-component score + BlobRef CIDv1 & signature verification
        val (signedScore, scoreCid) = OpenGamingAttestation.createSignedScore(
            score = LeaderboardScoreRecord(
                leaderboard = LB_RHYTHM,
                score = 2840,
                components = mapOf(
                    "ex-score" to ScoreComponentVal.points(2840),
                    "accuracy" to ScoreComponentVal.percentage(9942)
                ),
                dimensions = mapOf("mode" to "4k", "scroll" to "upscroll"),
                seed = "2026-11-21",
                replay = BlobRef(
                    ref = CidLinkWrapper("bafkreihbrikl5p3a3tmsgmt5ymprlxmbgo2vrw3xf3iokwoyhlfkj2jori"),
                    mimeType = "application/octet-stream",
                    size = 512
                ),
                recordedAt = "2026-11-21T12:05:00.000Z"
            ),
            playerDid = ALICE_DID,
            issuerDid = GAME_DID,
            signingKey = k1,
            rkey = "rhythm-pb-1"
        )
        assertEquals(EXPECTED_SCORE_CID, scoreCid)

        val tsSignedScore = signedScore.copy(
            signatures = listOf(signedScore.signatures!!.first().copy(signature = BytesWrapper(TS_SCORE_SIG)))
        )
        val tsScoreCheck = OpenGamingAttestation.verifyRecordAttestation(
            record = OpenGamingJson.decodeFromString(OpenGamingJson.encodeToString(tsSignedScore)),
            playerDid = ALICE_DID,
            recordUri = "at://$ALICE_DID/${OpenGamingConstants.Nsids.LEADERBOARD_SCORE}/rhythm-pb-1",
            publicDidKey = EXPECTED_K1_DID
        )
        assertTrue(tsScoreCheck.verified)

        // 4. Serverless P2P Co-Signed Match Result
        val (match1, aliceMatchCid) = OpenGamingAttestation.createSignedMatchResult(
            match = MatchResultRecord(
                game = GAME_URI,
                matchId = "duel-42",
                mode = "1v1-ranked",
                participants = listOf(
                    MatchParticipant(did = ALICE_DID, outcome = "win", score = 3, ratingBefore = 1500, ratingAfter = 1516),
                    MatchParticipant(did = BOB_DID, outcome = "loss", score = 1, ratingBefore = 1500, ratingAfter = 1484)
                ),
                playedAt = "2026-11-21T12:10:00.000Z"
            ),
            repositoryDid = ALICE_DID,
            issuerDid = ALICE_DID,
            signingKey = k1,
            rkey = "duel-42"
        )
        assertEquals(EXPECTED_MATCH_ALICE_CID, aliceMatchCid)

        val (coSigned, _, bobMatchCid) = OpenGamingAttestation.coSignMatchResult(
            match = match1,
            repositoryDid = ALICE_DID,
            signerDid = BOB_DID,
            signingKey = k2,
            issuedAt = "2026-11-21T12:10:05.000Z",
            rkey = "duel-42"
        )
        assertEquals(EXPECTED_MATCH_BOB_CID, bobMatchCid)

        val tsMatch = coSigned.copy(
            signatures = listOf(
                coSigned.signatures!![0].copy(signature = BytesWrapper(TS_MATCH_ALICE_SIG)),
                coSigned.signatures[1].copy(signature = BytesWrapper(TS_MATCH_BOB_SIG))
            )
        )
        val p2pCheck = OpenGamingAttestation.verifyMatchResult(
            record = OpenGamingJson.decodeFromString(OpenGamingJson.encodeToString(tsMatch)),
            repositoryDid = ALICE_DID,
            recordUri = "at://$ALICE_DID/${OpenGamingConstants.Nsids.MATCH_RESULT}/duel-42",
            participantDidKeys = mapOf(ALICE_DID to EXPECTED_K1_DID, BOB_DID to EXPECTED_K2_DID)
        )
        val verifiedMatch = assertIs<VerificationResult.Verified>(p2pCheck)
        assertEquals("multi-participant", verifiedMatch.verificationMethod)
    }

    @Test
    fun `enforces revocations, rkey binding, OAuth PKCE callback parsing, DPoP retry, and offline queue`() = runTest {
        val studioKey = OpenGamingSigningKey.generate()
        val (score, cid) = OpenGamingAttestation.createSignedScore(
            score = LeaderboardScoreRecord(
                leaderboard = LB_RHYTHM,
                score = 999,
                recordedAt = "2026-11-21T12:00:00.000Z"
            ),
            playerDid = ALICE_DID,
            issuerDid = GAME_DID,
            signingKey = studioKey,
            rkey = "locked-rkey"
        )
        val scoreJson = OpenGamingJson.decodeFromString<JsonObject>(OpenGamingJson.encodeToString(score))

        val rkeyFail = OpenGamingAttestation.verifyRecordAttestation(
            record = scoreJson,
            playerDid = ALICE_DID,
            recordUri = "at://$ALICE_DID/${OpenGamingConstants.Nsids.LEADERBOARD_SCORE}/copied-rkey",
            publicDidKey = studioKey.publicDidKey
        )
        assertFalse(rkeyFail.verified)
        assertEquals("rkey_mismatch", (rkeyFail as VerificationResult.Failed).error)

        val (_, rev) = OpenGamingAttestation.createRevocationRecord(
            scope = "attestation",
            playerDid = ALICE_DID,
            subjectUri = LB_RHYTHM,
            reason = "cheating",
            attestationCid = cid
        )
        val revFail = OpenGamingAttestation.verifyRecordAttestation(
            record = scoreJson,
            playerDid = ALICE_DID,
            recordUri = "at://$ALICE_DID/${OpenGamingConstants.Nsids.LEADERBOARD_SCORE}/locked-rkey",
            publicDidKey = studioKey.publicDidKey,
            revocations = listOf(RevocationWithOrigin(publisherDid = GAME_DID, value = rev))
        )
        assertFalse(revFail.verified)
        assertEquals("revoked", (revFail as VerificationResult.Failed).error)

        // Native OAuth PKCE + Deep Link Callback + DPoP Nonce auto-retry
        val pkce = OpenGamingClient.generatePkceChallenge()
        val authUrl = OpenGamingClient.buildNativeOAuthAuthorizeUrl(
            authorizationEndpoint = "https://bsky.social/oauth/authorize",
            clientIdMetadataUrl = "https://skyquest.example/oauth-client-metadata.json",
            redirectUri = "example.skyquest:/oauth/callback",
            pkce = pkce
        )
        assertTrue("code_challenge_method=S256" in authUrl)

        val callback = OpenGamingClient.parseOAuthCallbackUri(
            "example.skyquest:/oauth/callback?code=authcode123&state=${pkce.state}&iss=https%3A%2F%2Fbsky.social",
            pkce.state
        )
        assertEquals("authcode123", callback.code)

        var attempts = 0
        val dpopKey = OpenGamingSigningKey.generate()
        val client = OpenGamingClient(
            appViewBaseUrl = "https://opengaming.games",
            transport = { _, _, _, _, headers ->
                attempts++
                if (attempts == 1) {
                    HttpResponseData(401, """{"error":"use_dpop_nonce"}""", mapOf("DPoP-Nonce" to "fresh-nonce"))
                } else {
                    assertTrue(headers["DPoP"]!!.split('.').size == 3)
                    HttpResponseData(200, """{"uri":"at://did:plc:alice/col/rk","cid":"bafyok"}""")
                }
            },
            dpopKey = dpopKey
        )
        client.session = AtprotoSession(
            did = ALICE_DID,
            pdsUrl = "https://pds.example",
            accessToken = "dpop-token",
            isDpopBound = true
        )

        val tempQueue = Files.createTempFile("og_kt_queue", ".json").toFile()
        try {
            client.enqueueOfflineWrite(
                tempQueue,
                QueuedPdsWrite(
                    collection = OpenGamingConstants.Nsids.LEADERBOARD_SCORE,
                    rkey = "locked-rkey",
                    writeMode = "putRecord",
                    record = buildJsonObject { put("score", 999) }
                )
            )
            val flushed = client.flushOfflineQueue(tempQueue)
            assertEquals(1, flushed)
            assertEquals(2, attempts) // 1st got DPoP-Nonce 401 -> 2nd succeeded automatically!
        } finally {
            tempQueue.delete()
        }
    }
