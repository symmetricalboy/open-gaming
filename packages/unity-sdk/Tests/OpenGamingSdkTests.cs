        private static async Task TestCrossSdkGoldenVectorsAsync()
        {
            using var k1 = OpenGamingSigningKey.Load(Priv1Base64Url);
            using var k2 = OpenGamingSigningKey.Load(Priv2Base64Url);

            AssertEqual(ExpectedK1DidKey, k1.PublicDidKey, "k1 did:key");
            AssertEqual(ExpectedK2DidKey, k2.PublicDidKey, "k2 did:key");
            AssertEqual(Priv1Base64Url, k1.ExportPrivateKeyBase64Url(), "k1 export roundtrip");

            // 1. Deterministic rkey parity with @opengaming/sdk
            AssertEqual(
                "first-flight-1c5556424d2cb8f203ad",
                OpenGamingLeaderboards.GetUnlockRkey(AchFirstFlight),
                "GetUnlockRkey parity");
            AssertEqual(
                "rhythm-stage-1-best-2ee7912d017a611c2c1e",
                OpenGamingLeaderboards.GetOverwriteBestScoreRkey(
                    LbRhythm,
                    new Dictionary<string, string> { ["mode"] = "4k", ["scroll"] = "upscroll" },
                    "2026-11-21"),
                "GetOverwriteBestScoreRkey parity");

            // 2. Signed Unlock CIDv1 & TypeScript signature verification parity
            var (signedUnlock, unlockCid) = OpenGamingAttestation.CreateSignedUnlock(
                new AchievementUnlockRecord
                {
                    Achievement = AchFirstFlight,
                    Game = GameUri,
                    UnlockedAt = "2026-11-21T12:00:00.000Z",
                    Note = "Cleared on mobile!"
                },
                playerDid: AliceDid,
                issuerDid: GameDid,
                signingKey: k1,
                rkey: "first-flight-unlock");

            AssertEqual(ExpectedUnlockCid, unlockCid, "Unlock CIDv1 matches @opengaming/sdk byte-for-byte");

            // Verify C#-generated signature AND TypeScript-generated signature!
            var csharpVerify = await OpenGamingAttestation.VerifyRecordAttestationAsync(
                signedUnlock.ToRecordMap(),
                playerDid: AliceDid,
                recordUri: $"at://{AliceDid}/{OpenGamingConstants.Nsids.AchievementUnlock}/first-flight-unlock",
                publicDidKey: ExpectedK1DidKey);
            AssertTrue(csharpVerify.Verified, "C# unlock signature verifies");

            signedUnlock.Signatures![0].SignatureBase64 = TsUnlockSigBase64;
            string jsonRoundtrip = OpenGamingJson.Serialize(signedUnlock.ToRecordMap());
            var parsedUnlockMap = OpenGamingJson.ParseObject(jsonRoundtrip);
            var tsVerify = await OpenGamingAttestation.VerifyRecordAttestationAsync(
                parsedUnlockMap,
                playerDid: AliceDid,
                recordUri: $"at://{AliceDid}/{OpenGamingConstants.Nsids.AchievementUnlock}/first-flight-unlock",
                publicDidKey: ExpectedK1DidKey);
            AssertTrue(tsVerify.Verified, "TypeScript unlock signature verifies in C# after JSON roundtrip");

            // 3. Multi-component Score + BlobRef CIDv1 & signature parity
            var (signedScore, scoreCid) = OpenGamingAttestation.CreateSignedScore(
                new LeaderboardScoreRecord
                {
                    Leaderboard = LbRhythm,
                    Score = 2840,
                    RecordedAt = "2026-11-21T12:05:00.000Z",
                    Components = new Dictionary<string, ScoreComponentVal>
                    {
                        ["ex-score"] = ScoreComponentVal.Points(2840),
                        ["accuracy"] = ScoreComponentVal.Percentage(9942)
                    },
                    Dimensions = new Dictionary<string, string>
                    {
                        ["mode"] = "4k",
                        ["scroll"] = "upscroll"
                    },
                    Seed = "2026-11-21",
                    Replay = new BlobRef
                    {
                        CidLink = "bafkreihbrikl5p3a3tmsgmt5ymprlxmbgo2vrw3xf3iokwoyhlfkj2jori",
                        MimeType = "application/octet-stream",
                        Size = 512
                    }
                },
                playerDid: AliceDid,
                issuerDid: GameDid,
                signingKey: k1,
                rkey: "rhythm-pb-1");

            AssertEqual(ExpectedScoreCid, scoreCid, "Multi-component Score CIDv1 matches @opengaming/sdk byte-for-byte");
            signedScore.Signatures![0].SignatureBase64 = TsScoreSigBase64;
            var tsScoreVerify = await OpenGamingAttestation.VerifyRecordAttestationAsync(
                OpenGamingJson.ParseObject(OpenGamingJson.Serialize(signedScore.ToRecordMap())),
                playerDid: AliceDid,
                recordUri: $"at://{AliceDid}/{OpenGamingConstants.Nsids.LeaderboardScore}/rhythm-pb-1",
                publicDidKey: ExpectedK1DidKey);
            AssertTrue(tsScoreVerify.Verified, "TypeScript multi-component score signature verifies in C#");

            // 4. Serverless P2P Co-Signed Match Result parity
            var (matchStep1, matchAliceCid) = OpenGamingAttestation.CreateSignedMatchResult(
                new MatchResultRecord
                {
                    Game = GameUri,
                    MatchId = "duel-42",
