    internal sealed class MockTransport : IOpenGamingHttpTransport
    {
        public Func<string, string, string?, OpenGamingHttpResponse>? Handler { get; set; }

        public Task<OpenGamingHttpResponse> SendAsync(
            string method,
            string url,
            byte[]? body = null,
            string? contentType = null,
            IDictionary<string, string>? headers = null,
            CancellationToken cancellationToken = default)
        {
            string? bodyStr = body != null ? System.Text.Encoding.UTF8.GetString(body) : null;
            var res = Handler != null
                ? Handler(method, url, bodyStr)
                : new OpenGamingHttpResponse { StatusCode = 200, BodyText = "{}" };
            return Task.FromResult(res);
        }
    }

