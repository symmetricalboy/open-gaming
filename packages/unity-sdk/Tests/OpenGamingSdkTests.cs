            AssertTrue(p2pVerify.Verified, "P2P co-signed match verifies in C#");
            AssertEqual("multi-participant", p2pVerify.VerificationMethod, "VerificationMethod is multi-participant");
        }

        private static async Task TestSecurityDefensesAndRevocationsAsync()
        {
            using var gameKey = OpenGamingSigningKey.Generate();
            var (scoreRec, cid) = OpenGamingAttestation.CreateSignedScore(
                new LeaderboardScoreRecord
                {
                    Leaderboard = LbRhythm,
                    Score = 500,
                    RecordedAt = "2026-11-21T12:00:00.000Z"
                },
                playerDid: AliceDid,
                issuerDid: GameDid,
                signingKey: gameKey,
                rkey: "expected-rkey");

            // Reject rkey move attack
            var movedCheck = await OpenGamingAttestation.VerifyRecordAttestationAsync(
                scoreRec.ToRecordMap(),
                playerDid: AliceDid,
                recordUri: $"at://{AliceDid}/{OpenGamingConstants.Nsids.LeaderboardScore}/moved-rkey",
                publicDidKey: gameKey.PublicDidKey);
            AssertTrue(!movedCheck.Verified && movedCheck.Error == "rkey_mismatch", "Rejects rkey mismatch");

            // Reject surgical revocation
            var (_, rev) = OpenGamingAttestation.CreateRevocationRecord(
                scope: "attestation",
                playerDid: AliceDid,
                subjectUri: LbRhythm,
                reason: "exploit",
                attestationCid: cid);
            var revCheck = await OpenGamingAttestation.VerifyRecordAttestationAsync(
                scoreRec.ToRecordMap(),
                playerDid: AliceDid,
                recordUri: $"at://{AliceDid}/{OpenGamingConstants.Nsids.LeaderboardScore}/expected-rkey",
                publicDidKey: gameKey.PublicDidKey,
                revocations: new[] { rev });
            AssertTrue(!revCheck.Verified && revCheck.Error == "revoked", "Enforces surgical attestation revocation");

            // Fold ATProto labels & neg:true appeal
            var activeAfterAppeal = OpenGamingAttestation.ResolveActiveLabels(new[]
            {
                new AtprotoLabel { Src = GameDid, Uri = AliceDid, Val = "!cheat", Cts = "2026-11-21T10:00:00Z" },
                new AtprotoLabel { Src = GameDid, Uri = AliceDid, Val = "!cheat", Neg = true, Cts = "2026-11-21T10:05:00Z" }
            });
            AssertEqual(0, activeAfterAppeal.Count, "Label appeal negates prior !cheat label");
        }

        private static void TestLeaderboardFormattingPoliciesAndCompletion()
        {
            AssertEqual("1:06.03", OpenGamingLeaderboards.FormatScore(66032, new ScoreFormat { Kind = "time", TimeUnit = "milliseconds" }), "Time format");
            AssertEqual("+4", OpenGamingLeaderboards.FormatScore(4, new ScoreFormat { Kind = "numeric", SignedPrefix = true }), "SignedPrefix format");

            var lbDef = new LeaderboardDefinitionRecord
            {
                Game = GameUri,
                Name = "High Score",
                RecordPolicy = "overwriteBest",
                Timeframes = new List<string> { "allTime", "daily" },
                ScoreMin = 0,
                ScoreMax = 10000
            };
            var decision = OpenGamingLeaderboards.EvaluateScoreSubmission(LbRhythm, 250, lbDef);
            AssertTrue(decision.ShouldWrite && decision.WriteMode == "putRecord", "overwriteBest writes initial PB via putRecord");

            var defs = new List<(string, AchievementDefinitionRecord)>
            {
                (AchFirstFlight, new AchievementDefinitionRecord { Game = GameUri, Title = "Core", Tier = "gold" }),
                (AchFirstFlight + "-dlc", new AchievementDefinitionRecord { Game = GameUri, Title = "DLC", CompletionOptional = true, Tier = "bronze" })
            };
            var unlocks = new List<AchievementUnlockRecord>
            {
                new AchievementUnlockRecord { Achievement = AchFirstFlight, UnlockedAt = "2026-11-21T12:00:00Z" },
                new AchievementUnlockRecord { Achievement = AchFirstFlight + "-dlc", UnlockedAt = "2026-11-21T12:01:00Z" }
            };
            var profile = OpenGamingProfile.SummarizeActorProfile(AliceDid, unlocks, defs, "alice.test");
            AssertEqual(1, profile.CompletedGames, "Completed 100% core game");
            AssertEqual(1, profile.Games[0].BonusUnlockedCount ?? 0, "Tracks bonusUnlockedCount");
        }

        private static async Task TestClientOAuthPdsAndOfflineQueueAsync()
        {
            var pkce = OpenGamingClient.GeneratePkceChallenge();
            string authUrl = OpenGamingClient.BuildNativeOAuthAuthorizeUrl(
                "https://bsky.social/oauth/authorize",
                "https://skyquest.example/oauth-client-metadata.json",
                "example.skyquest:/oauth/callback",
                pkce);
            AssertTrue(authUrl.Contains("code_challenge_method=S256"), "PKCE S256 authorize URL");

            using var dpopKey = OpenGamingSigningKey.Generate();
            string dpopJwt = OpenGamingClient.CreateDpopProofJwt(dpopKey, "POST", "https://pds.example/xrpc/com.atproto.repo.putRecord", "nonce-1", "tok-1");
            AssertEqual(3, dpopJwt.Split('.').Length, "DPoP proof is a 3-part compact JWS");

            int putCalls = 0;
            var mockTransport = new MockTransport
            {
                Handler = (method, url, body) =>
                {
                    if (url.EndsWith("/xrpc/com.atproto.repo.putRecord"))
                    {
                        putCalls++;
                        return new OpenGamingHttpResponse
                        {
                            StatusCode = 200,
                            BodyText = "{\"uri\":\"at://did:plc:alice/games.opengaming.achievement.unlock/first\",\"cid\":\"bafy123\"}"
                        };
                    }
                    return new OpenGamingHttpResponse { StatusCode = 200, BodyText = "{\"did\":\"did:plc:alice\"}" };
                }
            };

            var client = new OpenGamingClient("https://opengaming.games", mockTransport, dpopKey)
            {
                Session = new AtprotoSession
                {
                    Did = AliceDid,
                    PdsUrl = "https://pds.example",
                    AccessToken = "tok-1",
                    IsDpopBound = true
                }
            };

            string queueFile = Path.Combine(Path.GetTempPath(), $"og_unity_queue_{Guid.NewGuid():N}.json");
            try
            {
                OpenGamingClient.EnqueueOfflineWrite(queueFile, new QueuedPdsWrite
                {
                    Collection = OpenGamingConstants.Nsids.AchievementUnlock,
                    Rkey = "first",
                    WriteMode = "putRecord",
                    Record = new Dictionary<string, object?> { ["$type"] = OpenGamingConstants.Nsids.AchievementUnlock, ["achievement"] = AchFirstFlight }
                });
                int flushed = await client.FlushOfflineQueueAsync(queueFile);
                AssertEqual(1, flushed, "Flushed 1 queued write");
                AssertEqual(1, putCalls, "Sent putRecord to PDS");
            }
            finally
            {
                if (File.Exists(queueFile)) File.Delete(queueFile);
            }
        }

        private static void AssertTrue(bool condition, string message)
        {
            if (!condition) throw new Exception($"Assertion failed: {message}");
            _passed++;
        }

        private static void AssertEqual<T>(T expected, T actual, string message)
        {
            if (!EqualityComparer<T>.Default.Equals(expected, actual))
                throw new Exception($"Assertion failed ({message}): expected '{expected}', got '{actual}'.");
            _passed++;
        }
